import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { execFile } from "node:child_process";
import { decodePng, imageToEscPosRaster } from "../escpos/png-to-raster.js";
import { EscPos } from "../escpos/commands.js";
import { htmlToPlainTextEscPos } from "../escpos/text-fallback.js";
import type { PaperWidth } from "../types.js";

export class HtmlRasterizer {
  private static browserPath: string | null = null;

  public static findBrowser(): string | null {
    if (this.browserPath && fs.existsSync(this.browserPath)) {
      return this.browserPath;
    }

    const winCandidates = [
      "C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe",
      "C:\\Program Files\\Microsoft\\Edge\\Application\\msedge.exe",
      "C:\\Program Files\\Google\\Chrome\\Application\\chrome.exe",
      "C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe",
      path.join(os.homedir(), "AppData\\Local\\Microsoft\\Edge\\Application\\msedge.exe"),
      path.join(os.homedir(), "AppData\\Local\\Google\\Chrome\\Application\\chrome.exe"),
    ];

    const posixCandidates = [
      "/usr/bin/google-chrome",
      "/usr/bin/chromium-browser",
      "/usr/bin/chromium",
      "/usr/bin/microsoft-edge",
      "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
      "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
    ];

    const list = process.platform === "win32" ? winCandidates : posixCandidates;
    for (const exe of list) {
      if (fs.existsSync(exe)) {
        this.browserPath = exe;
        return exe;
      }
    }

    return null;
  }

  public static async renderHtmlToEscPos(
    html: string,
    paperWidth: PaperWidth = "W80",
    customWidthMm?: number | null,
  ): Promise<Buffer> {
    const browser = this.findBrowser();

    if (!browser) {
      console.warn("[Rasterizer] No Chrome/Edge browser found. Using plain-text ESC/POS fallback.");
      return htmlToPlainTextEscPos(html);
    }

    const dotWidth = EscPos.resolveDotWidth(paperWidth, customWidthMm);
    const tempDir = os.tmpdir();
    const id = `receipt-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`;
    const htmlFile = path.join(tempDir, `${id}.html`);
    const pngFile = path.join(tempDir, `${id}.png`);

    try {
      // Injected CSS to enforce crisp black on white rendering and exact viewport width
      const styledHtml = html.replace(
        "</head>",
        `<style>
          html, body {
            margin: 0 !important;
            padding: 0 !important;
            background: #ffffff !important;
            color: #000000 !important;
            width: ${dotWidth}px !important;
            min-width: ${dotWidth}px !important;
            max-width: ${dotWidth}px !important;
            -webkit-print-color-adjust: exact !important;
          }
        </style></head>`,
      );

      fs.writeFileSync(htmlFile, styledHtml, "utf8");

      const fileUrl = `file:///${htmlFile.replace(/\\/g, "/")}`;

      const args = [
        "--headless=new",
        "--disable-gpu",
        "--no-sandbox",
        "--disable-setuid-sandbox",
        "--hide-scrollbars",
        `--window-size=${dotWidth},2400`,
        `--screenshot=${pngFile}`,
        fileUrl,
      ];

      await new Promise<void>((resolve, reject) => {
        execFile(browser, args, { timeout: 10000 }, (err) => {
          if (err) reject(err);
          else resolve();
        });
      });

      if (!fs.existsSync(pngFile)) {
        throw new Error("Raster screenshot was not generated by browser.");
      }

      const pngBuffer = fs.readFileSync(pngFile);
      const decoded = decodePng(pngBuffer);

      // Convert to ESC/POS raster: GS v 0
      const rasterData = imageToEscPosRaster(decoded, 185);

      return Buffer.concat([
        EscPos.INIT,
        rasterData,
        EscPos.FEED_3_LINES,
        EscPos.CUT_PARTIAL,
      ]);
    } catch (err) {
      console.error("[Rasterizer] Browser rasterization failed:", err);
      // Fallback to text ESC/POS
      return htmlToPlainTextEscPos(html);
    } finally {
      try {
        if (fs.existsSync(htmlFile)) fs.unlinkSync(htmlFile);
        if (fs.existsSync(pngFile)) fs.unlinkSync(pngFile);
      } catch {
        // cleanup ignore
      }
    }
  }
}
